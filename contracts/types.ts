/**
 * Shared data contracts (v1) between the Python pipeline and the web app.
 *
 * Rule: any change here goes through a PR to `contracts/` and the whole team is told.
 * JSON Schemas for the files live next to this file (*.schema.json).
 *
 * Files served from `web/public/data/`:
 *   manifest.json            -> DataManifest
 *   sites.json               -> SitesFile
 *   timeseries/<site_id>.json -> Timeseries
 *   layers.json              -> LayersManifest (+ the PNGs it points to under layers/)
 *
 * v1.1 (additive, nothing from v1 renamed; docs/10 J10 + §10 "whole Moon"):
 *   horizon/<site_id>.json   -> HorizonProfile   (terrain horizon, owner: Pablo)
 *   ephem/index.json         -> EphemIndex       (+ ephem/<YYYY>.bin Sun/Earth vectors, owner: Javi)
 *   grid/index.json          -> GridIndex        (+ grid/*.bin heat-map metrics, owner: Javi)
 *   MissionConfig            -> mission_config.schema.json (store `missionConfig`, Mission scenarios)
 */

// ---------------------------------------------------------------------------
// manifest.json — entry point: what was generated, from what, and for which window
// ---------------------------------------------------------------------------
export interface DataManifest {
  version: 1;
  /** true while the files are invented placeholders, false once the real pipeline writes them. */
  mock: boolean;
  generated_utc: string;
  /** Time window covered by every timeseries file. */
  time_range: { start_utc: string; end_utc: string; step_s: number };
  /** Datasets/kernels used to build the files (shown on the About page). */
  sources: string[];
}

// ---------------------------------------------------------------------------
// sites.json — candidate landing sites (owner: Javi / scoring)
// ---------------------------------------------------------------------------
export interface SiteMetrics {
  /** Fraction of time the Sun is above the local horizon over the time window, 0–1 (v1.1: mean of sun_frac; README "Window metrics"). */
  illum_pct: number;
  /** Fraction of time the Earth is above the local horizon + antenna margin over the time window, 0–1. */
  earth_vis_pct: number;
  /** Local slope in degrees. */
  slope_deg: number;
  /** Longest continuous period without sunlight, in hours. */
  max_dark_hours: number;
  /** Distance to the nearest permanently shadowed region, in km. */
  psr_dist_km: number;
}

/**
 * v1.1 window metrics, optional (docs/10 J5). Same window as the core metrics.
 * Kept apart from `SiteMetrics` so `keyof SiteMetrics` stays the five v1 keys.
 */
export interface SiteMetricsExtra {
  /** Mean of sun_frac · max(0, sun_el) over the window, degrees (energy proxy; 0 at night). */
  sun_el_mean_deg?: number;
  /** Longest continuous period without the Earth above horizon + antenna margin, hours. */
  max_blackout_hours?: number;
  /** Fraction of time with the Sun lit AND the Earth visible, 0–1. */
  sun_earth_pct?: number;
}

/** Where on the Moon a site is (docs/10 §10). south_pole: lat ≤ −80; north_pole: lat ≥ 80; else by |lon| ≤ 90. */
export type SiteRegion = 'south_pole' | 'north_pole' | 'near_side' | 'far_side';

/** Planning candidate vs. a place where a lander actually touched down. */
export type SiteKind = 'candidate' | 'historic_landing';

/**
 * One mission requirement evaluated on one site and window (docs/10 J6).
 * `margin` is relative and signed so that ≥ 0 passes and < 0 fails (exactly at the threshold passes, utility 0):
 * (value − threshold)/|threshold| when more is better, (threshold − value)/|threshold| when less is better
 * (plain difference if the threshold is 0). `null` value/margin = metric not available (see `pending`).
 */
export interface RequirementCheck {
  key: RequirementKey;
  ok: boolean;
  value: number | null;
  threshold: number;
  objective?: number;
  margin: number | null;
  /** The metric is pending (e.g. terrain not published yet): not used for validity or score. */
  pending?: boolean;
}

/** Machine-readable reasons; the UI maps them to human text. */
export type SiteReason =
  | 'slope_ok'
  | 'slope_high'
  | 'illum_ok'
  | 'illum_low'
  | 'earth_ok'
  | 'earth_low'
  | 'dark_ok'
  | 'dark_long'
  // v1.1 (generated by @/scoring from `checks`; `<metric>_pending` for pending metrics)
  | 'blackout_ok'
  | 'blackout_long'
  | 'sun_el_ok'
  | 'sun_el_low'
  | 'sun_earth_ok'
  | 'sun_earth_low'
  | 'psr_ok'
  | 'psr_far'
  | (string & {});

export interface Site {
  id: string;
  name: string;
  /** Planetocentric latitude, degrees (south is negative). */
  lat: number;
  /** East longitude, degrees in [-180, 180]. */
  lon: number;
  elev_m: number;
  /** Passes every non-pending requirement of DEFAULT_MISSION_CONFIG over the manifest window (README "Validity and score"). */
  valid: boolean;
  /** Weighted score 0–1 with DEFAULT_MISSION_CONFIG (Σwu/Σw). */
  score: number;
  metrics: SiteMetrics & SiteMetricsExtra;
  reasons: SiteReason[];
  /** Where the coordinates come from (paper, mission page, "custom", "mock"). */
  source?: string;
  // ---- v1.1, optional ----
  region?: SiteRegion;
  kind?: SiteKind;
  /** Free-text grouping, e.g. "Artemis III region (2024): Haworth". */
  group?: string;
  /** Requirement-by-requirement result with margins, for DEFAULT_MISSION_CONFIG (web/src/scoring/defaults.ts). */
  checks?: RequirementCheck[];
  /**
   * Metrics whose value is a placeholder until their source exists (e.g. slope_deg / psr_dist_km
   * before the terrain is published). They do not count for validity or score; the UI shows
   * "pending terrain" instead of the number.
   */
  pending_metrics?: RequirementKey[];
}

export interface SitesFile {
  version: 1;
  mock: boolean;
  generated_utc: string;
  /**
   * Default score weights; the UI may let users change them and re-rank client-side.
   * v1.1: may also carry weights for the extra metrics (e.g. max_blackout_hours).
   */
  weights: Record<keyof SiteMetrics, number> & Partial<Record<keyof SiteMetricsExtra, number>>;
  /**
   * v1.1: mission window that `Site.valid`, `score` and `checks` were evaluated over
   * (`missionWindow(DEFAULT_MISSION_CONFIG)`). `Site.metrics` stay over the manifest window.
   * Absent in v1 data: valid/score are then over the manifest window.
   */
  evaluation?: { start_utc: string; end_utc: string; config: 'default' };
  sites: Site[];
}

// ---------------------------------------------------------------------------
// timeseries/<site_id>.json — Sun/Earth sky position per time step (owner: Javi)
// ---------------------------------------------------------------------------
export interface Timeseries {
  version: 1;
  mock: boolean;
  site_id: string;
  /** Seconds between samples (3600 = hourly). */
  step_s: number;
  /** ISO 8601 UTC timestamps, one per sample. All arrays below have the same length. */
  t_utc: string[];
  /** Azimuth in degrees, clockwise from local north, [0, 360). */
  sun_az: number[];
  /** Elevation above the mathematical horizon, degrees. */
  sun_el: number[];
  earth_az: number[];
  earth_el: number[];
  /** 1 if the Sun clears the terrain horizon at that sample, else 0 (v1.1: sun_frac ≥ 0.5). */
  lit: (0 | 1)[];
  /**
   * 1 if the Earth clears the terrain horizon (+ antenna_margin_deg in v1.1) at that sample, else 0.
   * Optional in v1; required in real data (mock: false).
   */
  earth_visible?: (0 | 1)[];
  // ---- v1.1, optional ----
  /**
   * Visible fraction of the solar disc (radius 0.2666°) above the horizon, 0–1 (0.5 = centre on the
   * horizon). Only used for `illum_pct`; `lit` = sun_frac ≥ 0.5. Sunset/Earthset keep using lit/earth_visible.
   */
  sun_frac?: number[];
  /** Horizon used for lit/earth_visible: "flat (no terrain)" or the HorizonProfile source. */
  horizon_source?: string;
  /** Antenna margin baked into earth_visible, degrees. If it differs from missionConfig, rebuild with @/ephem. */
  antenna_margin_deg?: number;
}

// ---------------------------------------------------------------------------
// layers.json — raster overlays in south polar stereographic (owner: Pablo/Javi → Marta/Javi2)
// ---------------------------------------------------------------------------
export type PaletteStop = [position: number, color: string];

export interface LayerDef {
  id: string;
  label: string;
  /** Path relative to `data/`, e.g. "layers/elevation.png". */
  file: string;
  /**
   * How the PNG stores values. "gray8": 8-bit gray + alpha, value = min + gray/255 · (max - min);
   * alpha 0 = no data.
   */
  encoding: 'gray8' | 'gray16';
  kind: 'continuous' | 'categorical';
  units: string;
  value_range: [min: number, max: number];
  /** Color ramp over the normalised value [0, 1]. */
  palette: PaletteStop[];
  /** Labels for categorical layers, keyed by the raw value. */
  categories?: Record<string, string>;
  default_visible: boolean;
  default_opacity: number;
  description: string;
  source: string;
}

export interface LayersManifest {
  version: 1;
  mock: boolean;
  /** PROJ string of the raster grid. */
  projection: string;
  /** Forward projection used for pins: rho = 2R·tan((90° + lat)/2), x = rho·sin(lon), y = rho·cos(lon). */
  radius_m: number;
  /** [min_x, min_y, max_x, max_y] in projected metres. Row 0 of each PNG is max_y. */
  bounds_m: [number, number, number, number];
  /** Northernmost latitude covered (e.g. -80). */
  lat_limit: number;
  width_px: number;
  height_px: number;
  layers: LayerDef[];
}

